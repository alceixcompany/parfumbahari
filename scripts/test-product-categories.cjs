const assert = require('node:assert/strict');
const fs = require('node:fs');
require.extensions['.ts'] = (module, filename) => {
  const ts = require('typescript');
  module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText, filename);
};
const { productClassification, DEFAULT_PRODUCT_CATEGORIES } = require('../src/lib/productCategories.ts');
const { normalizeProduct } = require('../src/lib/normalizeProduct.ts');
const legacy = name => ({ name, concentration: '' });
assert.deepEqual(DEFAULT_PRODUCT_CATEGORIES.map(category => category.name), ['Bay', 'Bayan', 'Unisex']);
assert.deepEqual(productClassification(legacy('Tom Ford Oud Wood Edp 100 ML Erkek Parfüm')), { categoryId: 'erkek' });
assert.equal(productClassification(legacy('Amouage Guidance Edp 100 ml Kadın Outlet Parfüm')).categoryId, 'kadin');
assert.equal(productClassification(legacy('Creed Original Vetiver EDP UNİSEX 100 ML')).categoryId, 'unisex');
assert.equal(productClassification({ name: 'Özel parfüm', categoryId: 'bay' }).categoryId, 'erkek');
assert.equal(productClassification({ name: 'Özel parfüm', categoryId: 'bayan' }).categoryId, 'kadin');
assert.equal(productClassification({ name: 'Tom Ford Erkek Parfüm', categoryId: 'kadin' }).categoryId, 'kadin');
assert.equal(productClassification({ name: 'Tom Ford Erkek Parfüm', categoryId: 'old-custom-category' }).categoryId, 'erkek');
assert.deepEqual(productClassification({ name: 'Tom Ford Erkek Parfüm', categoryId: '' }), { categoryId: '' });
const malformed = normalizeProduct({ id: 'legacy', name: null, story: 42, description: 'Eski açıklama', image: 'bad-url', images: [null, { src: 'bad' }, '/parfum-bahari/rose.webp'], order: 'NaN', isActive: true });
assert.equal(malformed.image, '/parfum-bahari/rose.webp');
assert.equal(malformed.name, 'İsimsiz parfüm');
assert.equal(malformed.order, 0);
assert.equal(malformed.story, 'Eski açıklama');
assert.equal(malformed.slug, 'legacy');
console.log('PASS: three fixed categories, legacy IDs, explicit selection, retired custom-category fallback and malformed product normalization.');
